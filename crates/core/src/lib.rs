//! Расчётное ядро «Финансового календаря» (R2).
//!
//! Изолированный модуль: развёртка повторений, остатки, прогноз, резервы,
//! разрывы, цели, сценарии. Не зависит от UI, Tauri и хранилища.
//! Здесь пока пусто — наполняется задачами E1-T3 и E1-T6.

/// Версия ядра (используется как заглушка для проверки сборки и тестов).
pub fn version() -> &'static str {
    env!("CARGO_PKG_VERSION")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn core_is_callable_without_ui() {
        assert!(!version().is_empty());
    }
}
